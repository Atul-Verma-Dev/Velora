// ---- deterministic per-size stock ------------------------------------------
const DISTRIBUTION = [0.16, 0.22, 0.26, 0.18, 0.11, 0.07];

function derivedStockForSize(product, size) {
  if (!product.sizes.length) return 0;
  if (product.sizes.length === 1) return product.stock;
  const i = product.sizes.indexOf(size);
  if (i < 0) return 0; // a size the product doesn't come in is never in stock
  const weights = product.sizes.map((_, idx) => DISTRIBUTION[idx % DISTRIBUTION.length] || 0.1);
  const totalWeight = weights.reduce((sum, weight) => sum + weight, 0);
  const raw = (product.stock * weights[i]) / totalWeight;
  // A few SKUs intentionally have a sold-out extremity so variant handling is real.
  const soldOut = (product.id.charCodeAt(product.id.length - 1) + i) % 11 === 0;
  return soldOut ? 0 : Math.max(0, Math.round(raw));
}

// Real per-size inventory. Seed products derive it deterministically; the first
// stock mutation (order, seller adjustment) materialises it so sizes stop drifting.
export function ensureSizeStock(product) {
  if (product.sizeStock) return { ...product.sizeStock };
  return Object.fromEntries((product.sizes || []).map((s) => [s, derivedStockForSize(product, s)]));
}

export function stockForSize(product, size) {
  if (!product?.sizes?.length) return 0;
  if (product.sizeStock) return Math.max(0, Number(product.sizeStock[size]) || 0);
  return derivedStockForSize(product, size);
}

